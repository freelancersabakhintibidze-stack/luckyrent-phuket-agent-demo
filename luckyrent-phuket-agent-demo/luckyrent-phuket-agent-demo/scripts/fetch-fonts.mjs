// One-time font fetcher: downloads woff2 subsets from the Google Fonts CSS API
// and writes app/fonts.css with self-hosted @font-face rules (unicode-range kept).
// The app itself makes ZERO runtime requests to Google. Re-run only if you change families.
import { mkdir, writeFile } from "node:fs/promises";
import path from "node:path";

const ROOT = path.resolve(import.meta.dirname, "..");
const OUT_DIR = path.join(ROOT, "public", "fonts");
const CSS_OUT = path.join(ROOT, "app", "fonts.css");

const FAMILIES = [
  { css: "Cormorant+Garamond:wght@300..700", file: "cormorant-garamond" },
  { css: "Inter:wght@300..600", file: "inter" },
  { css: "JetBrains+Mono:wght@400..700", file: "jetbrains-mono" },
  { css: "Noto+Sans+Thai:wght@300..600", file: "noto-sans-thai" },
  { css: "Noto+Serif+Thai:wght@400..600", file: "noto-serif-thai" },
];

const UA =
  "Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/126.0 Safari/537.36";

const url =
  "https://fonts.googleapis.com/css2?family=" +
  FAMILIES.map((f) => f.css).join("&family=") +
  "&display=swap";

const res = await fetch(url, { headers: { "User-Agent": UA } });
if (!res.ok) throw new Error("css2 fetch failed: " + res.status);
const css = await res.text();

await mkdir(OUT_DIR, { recursive: true });

const blocks = css.split("/*").map((part) => {
  const m = part.match(/^\s*([a-z0-9-]+)\s*\*\/([\s\S]*)$/i);
  if (!m) return null;
  return { subset: m[1].trim(), body: m[2] };
}).filter(Boolean);

const faces = [];
let count = 0;
for (const { subset, body } of blocks) {
  const face = body.match(/@font-face\s*{([\s\S]*?)}/);
  if (!face) continue;
  const inner = face[1];
  const get = (prop) => {
    const m = inner.match(new RegExp(prop.replace("-", "\\-") + "\\s*:\\s*([^;]+);"));
    return m ? m[1].trim() : null;
  };
  const family = get("font-family")?.replace(/['"]/g, "");
  const weight = get("font-weight");
  const style = get("font-style");
  const srcUrl = inner.match(/url\((https:\/\/[^)]+\.woff2)\)/)?.[1];
  const unicodeRange = get("unicode-range");
  if (!family || !srcUrl) continue;
  const fam = FAMILIES.find((f) =>
    family.toLowerCase().startsWith(f.file.replace(/-/g, " ").split(" ").slice(0, family.split(" ").length).join("-").replace(/-/g, " ")) ||
    f.file === family.toLowerCase().replace(/\s+/g, "-")
  );
  const fileBase = fam ? fam.file : family.toLowerCase().replace(/\s+/g, "-");
  const fname = `${fileBase}-${subset}.woff2`;
  const buf = Buffer.from(await (await fetch(srcUrl, { headers: { "User-Agent": UA } })).arrayBuffer());
  await writeFile(path.join(OUT_DIR, fname), buf);
  faces.push({ family, weight, style, unicodeRange, fname });
  count++;
}

let out = "/* Self-hosted fonts. Generated by scripts/fetch-fonts.mjs. No runtime Google requests. */\n";
for (const f of faces) {
  out += `@font-face {\n  font-family: '${f.family}';\n  font-style: ${f.style};\n  font-weight: ${f.weight};\n  font-display: swap;\n  src: url('/fonts/${f.fname}') format('woff2');\n`;
  if (f.unicodeRange) out += `  unicode-range: ${f.unicodeRange};\n`;
  out += "}\n";
}
await writeFile(CSS_OUT, out);
console.log(`downloaded ${count} woff2 files, wrote ${CSS_OUT}`);
